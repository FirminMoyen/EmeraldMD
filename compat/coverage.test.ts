// Compares the runtime exports and class methods declared in the pinned
// `obsidian.d.ts` with what EmeraldMD's `obsidian` module provides, and writes
// docs/compat/api-coverage.md when UPDATE_COMPAT_DOCS is set.

import { readFileSync, writeFileSync } from 'node:fs';
import { obsidianModule } from '@emeraldmd/api';
import { describe, expect, it } from 'vitest';

interface Declared {
	name: string;
	kind: string;
	methods: string[];
}

/** Top-level runtime declarations (not interfaces or types) and the methods of each class. */
function readTypings(): Declared[] {
	const src = readFileSync('node_modules/obsidian/obsidian.d.ts', 'utf8').replace(/\/\*\*[\s\S]*?\*\//g, '');
	const lines = src.split('\n');
	const out: Declared[] = [];
	for (let i = 0; i < lines.length; i++) {
		const m = /^export (?:declare )?(?:abstract )?(class|function|const|let|enum) ([A-Za-z_$][\w$]*)/.exec(lines[i]!);
		if (!m) continue;
		const declared: Declared = { name: m[2]!, kind: m[1]!, methods: [] };
		if (m[1] === 'class') {
			for (let j = i + 1; j < lines.length && lines[j] !== '}'; j++) {
				// Abstract and optional members are the plugin's to implement, so they are not counted.
				const member = /^ {4}(?:static |protected |readonly |get |set )*([A-Za-z_$][\w$]*)(?:<[^>]*>)?\(/.exec(lines[j]!);
				if (member && member[1] !== 'constructor' && !/\b(private|abstract) /.test(lines[j]!)) declared.methods.push(member[1]!);
			}
			declared.methods = [...new Set(declared.methods)];
		}
		if (!out.some((d) => d.name === declared.name)) out.push(declared);
	}
	return out;
}

function hasMethod(cls: unknown, name: string): boolean {
	if (typeof cls !== 'function') return false;
	return name in (cls as { prototype: object }).prototype || name in cls;
}

describe('API coverage', () => {
	it('reports exports and methods from the typings', () => {
		const module = obsidianModule as unknown as Record<string, unknown>;
		const declared = readTypings();
		const rows: string[] = [];
		let exported = 0;
		let methods = 0;
		let methodsFound = 0;
		const missingExports: string[] = [];
		for (const d of declared) {
			const value = module[d.name];
			if (value !== undefined) exported++;
			else missingExports.push(d.name);
			const missing = d.methods.filter((m) => !hasMethod(value, m));
			methods += d.methods.length;
			methodsFound += d.methods.length - missing.length;
			const status = value === undefined ? '❌ missing' : missing.length ? `⚠️ ${d.methods.length - missing.length}/${d.methods.length} methods` : '✅';
			rows.push(`| \`${d.name}\` | ${d.kind} | ${status} | ${missing.map((m) => `\`${m}\``).join(', ')} |`);
		}
		// Plugins that load must at least find the base classes they extend.
		for (const name of ['Plugin', 'PluginSettingTab', 'Modal', 'ItemView', 'Setting', 'Notice', 'MarkdownView', 'FuzzySuggestModal', 'EditorSuggest']) {
			expect(missingExports, name).not.toContain(name);
		}
		if (process.env.UPDATE_COMPAT_DOCS) {
			const doc = [
				'# Plugin API coverage',
				'',
				'Generated by `npm run compat` (compat/coverage.test.ts) with `UPDATE_COMPAT_DOCS=1`, from the pinned',
				'`obsidian` typings (see `packages/api/API_VERSION`). It lists every runtime export (classes, functions,',
				'constants) and, for classes, which declared methods exist. Interfaces and types are compile-time only and',
				'are not listed. "Exists" means callable, not complete: see the notes in the source for partial behaviour.',
				'',
				`${exported} of ${declared.length} exports, ${methodsFound} of ${methods} class methods.`,
				'',
				'| Export | Kind | Status | Missing methods |',
				'|---|---|---|---|',
				...rows,
				'',
			].join('\n');
			writeFileSync('docs/compat/api-coverage.md', doc);
		}
	});
});
